// Cloudflare Email Sending (https://developers.cloudflare.com/email-service/). Sends through the
// Cloudflare API with the token OpenInbox already stores, so connecting it needs no second
// credential. Cloudflare generates the Message-ID and rejects it in `headers`, so replies thread
// through the References the send pipeline appends (the same as Resend).
import type { Env } from '../env';
import { loadSettings } from '../db/settings';
import { cfToken, Cloudflare, CfError, DEFAULT_CF_API } from '../cloudflare/client';
import {
  ProviderError,
  threadingHeaders,
  toBase64,
  type DomainSetup,
  type OutgoingAttachment,
  type OutgoingMessage,
  type ProviderAdapter,
  type SendResult,
} from './types';

// Nothing is stored per provider: the token and the account id come from the instance settings.
export type CloudflareConfig = Record<string, never>;

interface SendResponse {
  delivered?: string[];
  permanent_bounces?: string[];
  queued?: string[];
  suppressed_recipients?: string[];
  message_id?: string;
}

const sendPath = (accountId: string): string => `/accounts/${encodeURIComponent(accountId)}/email/sending/send`;

// Cloudflare error codes worth saying out loud instead of a bare HTTP status.
function providerError(e: unknown): ProviderError {
  if (e instanceof ProviderError) return e;
  if (!(e instanceof CfError)) return new ProviderError(e instanceof Error ? e.message : String(e));
  const code = e.errors[0]?.code;
  const detail = e.errors.map((x) => x.message).join('; ') || `HTTP ${e.status}`;
  const retryable = e.status === 429 || e.status >= 500;
  const failed = (message: string) => new ProviderError(message, retryable, e.status, code ? String(code) : undefined);
  switch (code) {
    case 10101:
      return failed('Cloudflare rejected the API token. Reconnect it in Integrations > Cloudflare.');
    case 10102:
      return failed('The Cloudflare API token needs the Email Sending permission. Recreate it from Integrations > Cloudflare.');
    case 10105:
      return failed('Cloudflare Email Sending requires the Workers Paid plan on this account.');
    case 10200:
      return failed('Cloudflare rejected the message: it is larger than 25 MB including attachments.');
    case 10203:
      return failed('Email Sending is not enabled for this domain in Cloudflare (Email Service > Email Sending), or it is switched off.');
    case 10207:
      return failed('Email Sending is paused for this Cloudflare account.');
    default:
      return new ProviderError(`Cloudflare: ${detail}`, retryable, e.status, code ? String(code) : undefined);
  }
}

function recipient(a: { name?: string; address: string }): { address: string; name?: string } {
  return a.name ? { address: a.address, name: a.name } : { address: a.address };
}

function attachment(a: OutgoingAttachment) {
  const base = { content: toBase64(a.content), filename: a.filename, type: a.contentType };
  return a.inline && a.contentId ? { ...base, disposition: 'inline', content_id: a.contentId } : { ...base, disposition: 'attachment' };
}

export class CloudflareAdapter implements ProviderAdapter {
  readonly type = 'cloudflare' as const;

  constructor(private env: Env) {}

  // The token and the account id live in the instance settings, so one Cloudflare connection serves
  // inbound routing and outbound sending alike.
  private async client() {
    const settings = await loadSettings(this.env.DB);
    const token = await cfToken(this.env, settings);
    if (!token) throw new ProviderError('Connect a Cloudflare API token first (Integrations > Cloudflare).');
    if (!settings.cfAccountId) throw new ProviderError('OpenInbox does not know your Cloudflare account yet. Finish setup first.');
    return { cf: new Cloudflare(token, this.env.CF_API_BASE || DEFAULT_CF_API), accountId: settings.cfAccountId };
  }

  // Listing the suppression list is the cheapest call behind the Email Sending permission; a token
  // without it, or an account that is not entitled, answers 401/403 instead of a list.
  async validate(): Promise<{ account?: string; note?: string }> {
    const { cf, accountId } = await this.client();
    try {
      await cf.request('GET', `/accounts/${encodeURIComponent(accountId)}/email/sending/suppressions?per_page=1`);
      return { account: 'Cloudflare Email Sending', note: 'Cloudflare accepted the token. Enable Email Sending for each domain you send from (Email Service > Email Sending in the dashboard).' };
    } catch (e) {
      throw providerError(e);
    }
  }

  async send(m: OutgoingMessage): Promise<SendResult> {
    const { cf, accountId } = await this.client();
    const headers = threadingHeaders(m);
    // Message-ID is generated by Cloudflare; sending it is rejected with E_HEADER_NOT_ALLOWED.
    delete headers['Message-ID'];
    let r: SendResponse;
    try {
      r = await cf.request<SendResponse>('POST', sendPath(accountId), {
        to: m.to.map(recipient),
        from: recipient(m.from),
        cc: m.cc.length ? m.cc.map(recipient) : undefined,
        bcc: m.bcc.length ? m.bcc.map(recipient) : undefined,
        reply_to: m.replyTo?.address,
        subject: m.subject,
        text: m.text || ' ',
        html: m.html ?? undefined,
        headers: Object.keys(headers).length ? headers : undefined,
        attachments: m.attachments.length ? m.attachments.map(attachment) : undefined,
      });
    } catch (e) {
      throw providerError(e);
    }
    const gone = [...(r.permanent_bounces ?? []), ...(r.suppressed_recipients ?? [])];
    if (gone.length && !(r.delivered?.length || r.queued?.length)) {
      throw new ProviderError(`Cloudflare did not accept the message for ${gone.join(', ')}.`);
    }
    return { providerMessageId: r.message_id?.replace(/^<|>$/g, '') ?? null };
  }

  // Cloudflare exposes sending and suppressions over the API, but not onboarding a sending domain:
  // that is the dashboard or `wrangler email sending enable`. The provider row is hidden from the
  // domain setup UI (hasDomainApi: false), so these only guard the service layer.
  async addDomain(domain: string): Promise<DomainSetup> {
    throw new ProviderError(`Enable Email Sending for ${domain} in the Cloudflare dashboard (Email Service > Email Sending), then send from it here.`);
  }

  async checkDomain(domain: string): Promise<DomainSetup> {
    throw new ProviderError(`Cloudflare does not verify sending domains over the API. Check ${domain} in the Cloudflare dashboard.`);
  }
}
