// First-run setup: checks the deployment, then lets the owner claim the instance by creating the
// admin mailbox on one of their domains.
//
// Nothing is asked on the deploy form. The owner proves the deployment is theirs by pasting a
// Cloudflare token that can see this very Worker; setup then generates ENCRYPTION_KEY, saves it as
// the Worker's secret through the API and shows it once as the recovery key. Claiming needs that
// key back, so nobody who merely finds the workers.dev URL first can take over a fresh instance.
// A deployment whose ENCRYPTION_KEY was set by hand keeps it.
import type { Env } from '../env';
import { loadSettings, saveSettings, type AppSettings } from '../db/settings';
import { first } from '../db/db';
import { CfError, Cloudflare, cfFromEnv, DEFAULT_CF_API } from '../cloudflare/client';
import { checkPermissions, listZones, verifyToken, type PermissionCheck } from '../cloudflare/token';
import { detectWorker, putWorkerSecret } from '../cloudflare/workers';
import { decrypt, encrypt, hex, randomBytes } from '../lib/crypto';
import { errorMessage, HttpError } from '../lib/errors';

export interface CheckResult {
  ok: boolean;
  message: string;
  warning?: boolean;
  pending?: boolean;
}

// missing: not set yet (created when the token is connected). activating: generated, but this
// isolate doesn't run with it yet. generated: generated by setup and live. set: set by hand.
export type KeyState = 'missing' | 'activating' | 'generated' | 'set';

export interface SetupStatus {
  setupComplete: boolean;
  checks: {
    database: CheckResult;
    encryptionKey: CheckResult & { state: KeyState };
    cloudflare: CheckResult & { source: 'secret' | 'stored' | null };
    worker: CheckResult & { name?: string; subdomain?: string | null; accountName?: string };
    zones: CheckResult & { count: number };
  };
  permissions: PermissionCheck[];
  zones: { id: string; name: string; status: string }[];
}

export async function setupStatus(env: Env, host: string, refresh = false): Promise<SetupStatus> {
  const checks = {} as SetupStatus['checks'];
  let settings: AppSettings | null = null;

  try {
    await first(env.DB, 'SELECT COUNT(*) AS n FROM users');
    settings = await loadSettings(env.DB, true);
    checks.database = { ok: true, message: 'Database is ready.' };
  } catch (e) {
    checks.database = { ok: false, message: `Database error: ${errorMessage(e)}` };
  }

  const state = settings ? await keyState(env, settings) : 'missing';
  const key = env.ENCRYPTION_KEY ?? '';
  checks.encryptionKey =
    state === 'missing'
      ? { ok: false, pending: true, state, message: 'Created for you when you connect Cloudflare below.' }
      : state === 'activating'
        ? { ok: false, pending: true, state, message: 'Saving the new key to this Worker. This takes a few seconds.' }
        : state === 'generated'
          ? { ok: true, state, message: 'Recovery key created and saved to this Worker as ENCRYPTION_KEY.' }
          : key.length < 32
            ? { ok: true, warning: true, state, message: `ENCRYPTION_KEY is short (${key.length} characters). 32 or more is recommended.` }
            : { ok: true, state, message: 'Encryption key is set.' };

  const empty: SetupStatus = {
    setupComplete: !!settings?.setupCompletedAt,
    checks: {
      ...checks,
      cloudflare: {
        ok: false,
        source: null,
        message:
          state === 'missing' ? 'No Cloudflare API token yet. Paste one below.' : state === 'activating' ? 'Waiting for the new key.' : 'Waiting for the checks above.',
      },
      worker: { ok: false, message: 'Waiting for the Cloudflare token.' },
      zones: { ok: false, count: 0, message: 'Waiting for the Cloudflare token.' },
    },
    permissions: [],
    zones: [],
  };
  if (!settings || !checks.encryptionKey.ok) return empty;

  let cf;
  try {
    cf = await cfFromEnv(env, settings);
  } catch (e) {
    empty.checks.cloudflare = { ok: false, source: 'stored', message: errorMessage(e) };
    return empty;
  }
  if (!cf) {
    empty.checks.cloudflare = { ok: false, source: null, message: 'No Cloudflare API token yet. Paste one below.' };
    return empty;
  }
  const source = env.CF_API_TOKEN ? 'secret' : 'stored';
  const token = await verifyToken(cf);
  if (!token.valid) {
    empty.checks.cloudflare = { ok: false, source, message: token.message ?? 'Cloudflare rejected the token.' };
    return empty;
  }
  checks.cloudflare = { ok: true, source, message: `Token is valid (${token.kind === 'account' ? 'account' : 'user'} token).` };

  let identity = settings.cfAccountId && settings.cfWorkerName && !refresh
    ? { accountId: settings.cfAccountId, accountName: settings.cfAccountName ?? '', workerName: settings.cfWorkerName, workersSubdomain: settings.cfWorkersSubdomain, d1Id: settings.cfD1Id }
    : null;
  if (!identity) {
    try {
      identity = await detectWorker(cf, host, env.WORKER_NAME);
      await saveSettings(env.DB, {
        cfAccountId: identity.accountId,
        cfAccountName: identity.accountName,
        cfWorkerName: identity.workerName,
        cfWorkersSubdomain: identity.workersSubdomain,
        cfD1Id: identity.d1Id,
      });
    } catch (e) {
      checks.worker = { ok: false, message: errorMessage(e) };
    }
  }
  if (identity) {
    checks.worker = {
      ok: true,
      name: identity.workerName,
      subdomain: identity.workersSubdomain,
      accountName: identity.accountName,
      message: `Found the ${identity.workerName} Worker in ${identity.accountName || 'your account'}.`,
    };
  }

  let zones: SetupStatus['zones'] = [];
  try {
    zones = (await listZones(cf, identity?.accountId)).map((z) => ({ id: z.id, name: z.name, status: z.status }));
    checks.zones = zones.length
      ? { ok: true, count: zones.length, message: `${zones.length} domain${zones.length === 1 ? '' : 's'} found.` }
      : { ok: false, count: 0, message: 'No domains in this account. Add your domain to Cloudflare first, then reload.' };
  } catch (e) {
    checks.zones = { ok: false, count: 0, message: errorMessage(e) };
  }

  const permissions = identity ? await checkPermissions(cf, identity.accountId, zones.find((z) => z.status === 'active')?.id ?? zones[0]?.id ?? null) : [];
  return { setupComplete: !!settings.setupCompletedAt, checks, permissions, zones };
}

export async function keyState(env: Env, settings: AppSettings): Promise<KeyState> {
  if (!settings.keyGeneratedAt) return env.ENCRYPTION_KEY ? 'set' : 'missing';
  if (!env.ENCRYPTION_KEY || !settings.keyCheck) return 'activating';
  try {
    await decrypt(env, settings.keyCheck);
    return 'generated';
  } catch {
    // A newer key is still on its way to this isolate.
    return 'activating';
  }
}

// Connects a token pasted on the setup page. It must be able to see this Worker: that is the proof
// of ownership. While setup owns the key, connecting also generates a new ENCRYPTION_KEY (unless
// one is live and the caller only changes the token) and returns it, once, as the recovery key.
export async function connectToken(env: Env, host: string, token: string, newKey = false): Promise<{ recoveryKey: string | null }> {
  const cf = new Cloudflare(token, env.CF_API_BASE || DEFAULT_CF_API);
  const check = await verifyToken(cf);
  if (!check.valid) throw new HttpError(400, 'invalid_token', check.message ?? 'Cloudflare rejected this token.');
  let identity;
  try {
    identity = await detectWorker(cf, host, env.WORKER_NAME);
  } catch (e) {
    if (e instanceof CfError && !e.isAuth) throw e;
    throw new HttpError(400, 'worker_not_found', `This token can't see this Worker, so it can't prove the deployment is yours. ${errorMessage(e)}`);
  }

  const state = await keyState(env, await loadSettings(env.DB, true));
  const generate = state === 'missing' || state === 'activating' || (state === 'generated' && newKey);
  let recoveryKey: string | null = null;
  let keyEnv = env;
  if (generate) {
    recoveryKey = hex(randomBytes(32));
    try {
      await putWorkerSecret(cf, identity.accountId, identity.workerName, 'ENCRYPTION_KEY', recoveryKey);
    } catch (e) {
      if (e instanceof CfError && e.isAuth) {
        throw new HttpError(400, 'cloudflare_permission', 'The token needs Account → Workers Scripts → Edit to save the recovery key to this Worker.');
      }
      throw e;
    }
    keyEnv = { ...env, ENCRYPTION_KEY: recoveryKey, ENCRYPTION_KEY_PREVIOUS: undefined };
  }
  await saveSettings(env.DB, {
    cfTokenEnc: await encrypt(keyEnv, token.trim()),
    cfAccountId: identity.accountId,
    cfAccountName: identity.accountName,
    cfWorkerName: identity.workerName,
    cfWorkersSubdomain: identity.workersSubdomain,
    cfD1Id: identity.d1Id,
    ...(generate ? { keyGeneratedAt: Date.now(), keyCheck: await encrypt(keyEnv, 'openinbox') } : {}),
  });
  return { recoveryKey };
}
